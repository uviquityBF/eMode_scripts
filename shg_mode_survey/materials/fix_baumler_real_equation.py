"""Fixes ScAlN_Baumler2019_sellmeier_fits.json's `emode_equation_real` field: regenerates it to be
pole-free across the SH band (215-235 nm), where the project actually needs to evaluate it for
EMode's FDM mode solve.

Root cause (found 2026-10-14, debugging a reproducible EMode "eigenvalue solver crashed, not
enough memory" error that turned out to have nothing to do with memory -- system had >1TB free):
`fit_baumler_sellmeier.py`'s `emode_equation_real` is generated by literally dropping the damping
term (g_j -> 0) from the fitted damped-Lorentzian model. The damped (complex) form never truly
diverges at a resonance (the damping term keeps the denominator's imaginary part nonzero even
exactly at lam0); the undamped form is a genuine pole there. Several compositions' fitted
resonances (lam0) land inside or near 215-235 nm (e.g. 32% Sc has oscillators at 0.204, 0.220,
0.197 um -- right in the band), so the real-only equation we're forced to feed EMode (a complex
refractive_index_equation crashes em.FDM() outright, confirmed project-wide) evaluates to
unphysical values there: n=10.8 at 220nm, a complex number at 218nm, etc. for the 32% fit.

Fix: refit a SEPARATE undamped 4-oscillator real Sellmeier model, not to the raw digitized data,
but to Re(sqrt(eps_damped(lam))) sampled densely across the full fit range -- i.e. match the real
part of the ALREADY-VALIDATED damped model (smooth and well-behaved everywhere by construction),
rather than re-deriving from noisy digitized points. Each oscillator's lam0 is constrained via a
box-bound combinatorial search (scipy least_squares respects bounds throughout optimization, so a
box that excludes [FORBIDDEN_LO, FORBIDDEN_HI] by construction keeps the fitted pole out of the
band no matter where the optimizer lands) to sit either below 0.213 um or above 0.237 um (a 2nm
guard band on each side of 215-235nm) -- never inside it. Tries every combination of
below/above per oscillator (where both sides exist within that oscillator's original bound range)
and keeps the lowest-residual fit.

emode_equation_complex is left untouched (it's only ever eval()'d in Python for the post-solve
bulk-loss perturbation, never fed to EMode, and the damped model is already a good fit to the real
n,k data). Only emode_equation_real is regenerated; the json gains a `real_equation_fix` block per
composition documenting the pole check and fit quality.

Usage: python materials/fix_baumler_real_equation.py
"""
import json
import os

import numpy as np
from scipy.optimize import least_squares

HERE = os.path.dirname(os.path.abspath(__file__))
JSON_PATH = os.path.join(HERE, 'ScAlN_Baumler2019_sellmeier_fits.json')

LAM_MIN_NM, LAM_MAX_NM = 207.0, 600.0
FORBIDDEN_LO_UM, FORBIDDEN_HI_UM = 0.213, 0.237  # 215-235nm SH band + 2nm guard each side
N_OSC = 4
N_FIT_WAVELENGTHS = 400

# same oscillator-slot bound ranges as fit_baumler_sellmeier.py's fit_one()
OSC_BOUNDS_UM = [(0.12, 0.30), (0.12, 0.32), (0.08, 0.22), (0.03, 0.15)]


def eps_damped(p, lam_um):
    eps = p[0] + 0j
    P = p[1]
    for j in range(N_OSC):
        B, lam0, g = p[2 + 3 * j:5 + 3 * j]
        eps = eps + B * lam_um ** 2 / (lam_um ** 2 - lam0 ** 2 - 1j * g * (lam0 / lam_um) ** P * lam_um)
    return eps


def eps_undamped(q, lam_um):
    eps = q[0]
    for j in range(N_OSC):
        B, lam0 = q[1 + 2 * j:3 + 2 * j]
        eps = eps + B * lam_um ** 2 / (lam_um ** 2 - lam0 ** 2)
    return eps


def osc_side_ranges(lo, hi):
    """Sub-ranges of [lo, hi] that avoid [FORBIDDEN_LO_UM, FORBIDDEN_HI_UM], each >= 5nm wide."""
    sides = []
    if lo < FORBIDDEN_LO_UM:
        sides.append((lo, min(hi, FORBIDDEN_LO_UM)))
    if hi > FORBIDDEN_HI_UM:
        sides.append((max(lo, FORBIDDEN_HI_UM), hi))
    return [s for s in sides if s[1] - s[0] >= 0.005]


def fit_real_pole_free(lam_um, n_target):
    """Undamped 4-oscillator real Sellmeier fit to n_target(lam_um), every oscillator's lam0
    boxed into a pole-free sub-range. Tries all combinations, returns the best (lowest cost)."""
    side_options = [osc_side_ranges(lo, hi) for lo, hi in OSC_BOUNDS_UM]

    def resid(q):
        eps = eps_undamped(q, lam_um)
        eps = np.where(eps < 0.1, 0.1, eps)  # guard against a stray negative eps mid-optimization
        return np.sqrt(eps) - n_target

    best = None
    import itertools
    for combo in itertools.product(*[range(len(opts)) for opts in side_options]):
        lo_q, hi_q = [0.3], [5.0]
        p0 = [2.0]
        for j, side_idx in enumerate(combo):
            s_lo, s_hi = side_options[j][side_idx]
            lo_q += [0.0, s_lo]
            hi_q += [15.0, s_hi]
            p0 += [1.0, 0.5 * (s_lo + s_hi)]
        r = least_squares(resid, p0, bounds=(lo_q, hi_q), x_scale='jac', max_nfev=8000)
        if best is None or r.cost < best.cost:
            best = r
    return best.x


def _fixed(v, sig=6):
    if v == 0:
        return '0'
    import math
    decimals = max(0, sig - 1 - int(math.floor(math.log10(abs(v)))))
    return f"{v:.{decimals}f}"


def emode_equation_real_from_q(q):
    terms = [_fixed(q[0])]
    for j in range(N_OSC):
        B, lam0 = q[1 + 2 * j:3 + 2 * j]
        terms.append(f"{_fixed(B)}*x**2/(x**2-{_fixed(lam0 ** 2)})")
    return f"({'+'.join(terms)})**0.5"


def pole_check(eq, lo_nm=213.0, hi_nm=237.0, step_nm=0.1):
    bad = []
    for wl_nm in np.arange(lo_nm, hi_nm + step_nm, step_nm):
        x = wl_nm / 1000.0
        n = eval(eq, {'x': x})
        if abs(np.imag(n)) > 1e-6 or not np.isfinite(np.real(n)) or np.real(n) > 6 or np.real(n) < 1.0:
            bad.append(round(float(wl_nm), 2))
    return bad


def main():
    with open(JSON_PATH) as f:
        d = json.load(f)

    lam_f_um = np.linspace(LAM_MIN_NM, LAM_MAX_NM, N_FIT_WAVELENGTHS) / 1000.0

    print(f"{'comp':>6} {'rms_vs_damped':>14} {'max_abs_err':>12} {'poles_in_SH_band':>18} {'verdict'}")
    for comp, fit in d['fits'].items():
        p = fit['params']
        pvec = [p['eps_inf'], p['damping_power_P']]
        for o in p['oscillators']:
            pvec += [o['B'], o['lam0_um'], o['g_um']]
        pvec = np.array(pvec, float)

        n_true = eps_damped(pvec, lam_f_um) ** 0.5
        n_true_real = n_true.real

        q = fit_real_pole_free(lam_f_um, n_true_real)
        eq_real = emode_equation_real_from_q(q)

        n_fit = eval(eq_real, {'x': lam_f_um})
        rms = float(np.sqrt(np.mean((n_fit - n_true_real) ** 2)))
        max_err = float(np.max(np.abs(n_fit - n_true_real)))
        bad = pole_check(eq_real)
        verdict = 'CLEAN' if not bad else f'{len(bad)} bad pts'
        print(f"{comp:>6} {rms:>14.5f} {max_err:>12.5f} {str(bad[:3]) + ('...' if len(bad) > 3 else ''):>18} {verdict}")

        fit['emode_equation_real'] = eq_real
        fit['real_equation_fix'] = {
            'method': 'undamped 4-osc Sellmeier refit to Re(sqrt(eps_damped)), oscillator lam0 '
                      'boxed out of [%.3f, %.3f] um (215-235nm SH band + 2nm guard)' % (
                          FORBIDDEN_LO_UM, FORBIDDEN_HI_UM),
            'rms_n_vs_damped_model': rms,
            'max_abs_err_n_vs_damped_model': max_err,
            'pole_check_215_235nm_bad_points': bad,
            'believable': max_err < 0.15 and not bad,
        }

    with open(JSON_PATH, 'w') as f:
        json.dump(d, f, indent=1)
    print(f'\nwrote {JSON_PATH}')


if __name__ == '__main__':
    main()
